def all_equipment() -> list[str]:
    """Полный список номенклатуры, встречающейся в сегментах."""
    seen: list[str] = []
    for seg in SEGMENTS:
        for item in seg["equipment"]:
            if item not in seen:
                seen.append(item)
    return seen


def segments_for_equipment(equipment: str) -> list[dict]:
    """Сегменты, которым нужна конкретная техника. Регистр не важен."""
    needle = equipment.strip().lower()
    return [s for s in SEGMENTS if any(needle in e.lower() for e in s["equipment"])]


def find_segments(names: list[str] | None) -> list[dict]:
    """Отбор сегментов по названию. Пустой список означает «все сегменты»."""
    if not names:
        return list(SEGMENTS)
    picked: list[dict] = []
    for name in names:
        needle = name.strip().lower()
        for seg in SEGMENTS:
            if needle in seg["segment"].lower() and seg not in picked:
                picked.append(seg)
    return picked
